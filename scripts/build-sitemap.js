#!/usr/bin/env node
'use strict';

// ============================================================
// build-sitemap.js
// Run: node scripts/build-sitemap.js          (writes sitemap.xml)
//      node scripts/build-sitemap.js --check  (compares, writes nothing)
// Reads data/*.json (same loader as scripts/build-search-index.js) and writes
// sitemap.xml at the repo root: home, public static pages, the 6 categories
// and every product.
// URLs have no .html: vercel.json sets cleanUrls, so /x.html redirects to /x.
// Product URLs match the canonical set in js/product-page.js.
// Category slugs are the ones the site links to and js/category-page.js
// resolves (categoryInfo + the filter).
// Pages with noindex, private pages (cart, checkout, success, account,
// loyalty), 404 and conventions are left out on purpose.
// No external dependencies — only Node.js built-ins.
// Exit codes: 0 = ok (or sitemap up to date), 1 = sitemap out of date or
// invalid product data, 2 = could not read the data or write the sitemap.
// ============================================================

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DATA_DIR = path.join(ROOT, 'data');
const SITEMAP_PATH = path.join(ROOT, 'sitemap.xml');
const IGNORED_FILES = new Set(['category-messages.json']);
const BASE_URL = 'https://electricink.ie';

const STATIC_PAGES = [
  '/',
  '/about-us',
  '/black-cat-friday',
  '/contact-us',
  '/faq',
  '/howtousecosmetics',
  '/shipping-information',
  '/returns-refunds',
  '/terms-conditions',
  '/privacy-policy',
  '/cookie-policy'
];

const CATEGORY_SLUGS = [
  'cosmetics',
  'cartridges',
  'inks',
  'accessories',
  'machines',
  'power-supplies'
];

const CHECK_MODE = process.argv.slice(2).includes('--check');

// ────────── Data loading (same as build-search-index.js) ──────────

function loadSiteProducts() {
  const products = [];
  const files = fs.readdirSync(DATA_DIR).filter((f) => f.endsWith('.json') && !IGNORED_FILES.has(f));
  for (const file of files) {
    const obj = JSON.parse(fs.readFileSync(path.join(DATA_DIR, file), 'utf8'));
    for (const [pid, product] of Object.entries(obj)) {
      if (product && typeof product === 'object') products.push({ file, pid, product });
    }
  }
  return products;
}

// ────────── Sitemap ──────────

function xmlEscape(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function buildUrls(siteProducts, problems) {
  const productIds = [];
  const seen = new Set();

  for (const { file, pid, product } of siteProducts) {
    // js/product-page.js looks the product up by its key in the JSON file
    // (allProducts[productId]) and builds the canonical from product.id.
    if (product.id !== pid) problems.push(`${file}: key ${pid} differs from id ${product.id}`);
    if (seen.has(pid)) problems.push(`${file}: duplicate id ${pid}`);
    seen.add(pid);
    productIds.push(pid);
  }

  // Stable order so a rebuild only changes the lines of products that changed
  productIds.sort();

  return [
    ...STATIC_PAGES.map((p) => BASE_URL + p),
    ...CATEGORY_SLUGS.map((slug) => `${BASE_URL}/category?cat=${encodeURIComponent(slug)}`),
    ...productIds.map((id) => `${BASE_URL}/products?id=${encodeURIComponent(id)}`)
  ];
}

function serialize(urls) {
  return '<?xml version="1.0" encoding="UTF-8"?>\n'
    + '<!-- Generated by scripts/build-sitemap.js from data/*.json. Do not edit by hand: run npm run build:sitemap -->\n'
    + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    + urls.map((u) => `  <url><loc>${xmlEscape(u)}</loc></url>`).join('\n')
    + '\n</urlset>\n';
}

// ────────── Run ──────────

function run() {
  let siteProducts;
  try {
    siteProducts = loadSiteProducts();
  } catch (e) {
    console.error(`ERROR could not read product data in ${DATA_DIR}: ${e.message}`);
    process.exit(2);
  }

  const problems = [];
  const urls = buildUrls(siteProducts, problems);
  if (problems.length > 0) {
    problems.forEach((p) => console.error(`ERROR ${p}`));
    process.exit(1);
  }

  const output = serialize(urls);
  const rel = path.relative(process.cwd(), SITEMAP_PATH);

  if (CHECK_MODE) {
    let current = null;
    try {
      current = fs.readFileSync(SITEMAP_PATH, 'utf8');
    } catch (e) {
      console.error(`ERROR ${rel} not found. Run: npm run build:sitemap`);
      process.exit(1);
    }
    if (current !== output) {
      console.error(`ERROR ${rel} is out of date with data/*.json. Run: npm run build:sitemap`);
      process.exit(1);
    }
    console.log(`SITEMAP: up to date (${urls.length} URLs)`);
    process.exit(0);
  }

  try {
    fs.writeFileSync(SITEMAP_PATH, output, 'utf8');
  } catch (e) {
    console.error(`ERROR could not write ${rel}: ${e.message}`);
    process.exit(2);
  }
  console.log(`SITEMAP: wrote ${rel} (${urls.length} URLs, ${Buffer.byteLength(output)} bytes)`);
  process.exit(0);
}

run();
